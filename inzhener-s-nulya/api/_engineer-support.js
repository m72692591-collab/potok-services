export function engineerSupportAnswer(question){
  const q=String(question||'').trim().toLowerCase().replace(/ё/g,'е');
  if(!q)return{
    category:'empty',
    answer:'Напишите вопрос про AutoCAD, Primavera P6, выбор курса, оплату или получение материалов.',
    suggestions:['Что выбрать: AutoCAD или Primavera?','Я полный новичок','Как получить курс после оплаты?']
  };
  let best=null,bestScore=0;
  for(const topic of TOPICS){
    let score=0;
    for(const raw of topic.words){
      const w=raw.toLowerCase().replace(/ё/g,'е');
      if(q.includes(w))score+=Math.max(2,w.split(/\s+/).length);
    }
    if(score>bestScore){best=topic;bestScore=score}
  }
  if(best)return{
    category:best.id,
    answer:best.answer,
    suggestions:best.id.startsWith('autocad')
      ?['Какие команды AutoCAD учить первыми?','Как проверить масштаб?','Что выбрать после бесплатного урока?']
      :best.id.startsWith('primavera')
        ?['Что такое WBS?','Почему двигается дата окончания?','Какой курс выбрать?']
        :['Попробовать бесплатный набор','Что входит в AutoCAD?','Что входит в Primavera P6?']
  };
  return{
    category:'fallback',
    answer:'Чтобы не придумывать ответ, уточню границы: автоматический помощник консультирует по курсам «Инженер с нуля», оплате и доступу, а также по базовым учебным вопросам AutoCAD и Primavera P6. Сформулируйте вопрос короче, например: «как проверить размер в AutoCAD», «что такое WBS» или «какой курс выбрать».',
    suggestions:['Как проверить размер в AutoCAD?','Что такое WBS?','Какой курс выбрать?']
  };
}
